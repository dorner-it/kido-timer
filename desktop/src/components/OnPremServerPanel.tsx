import { useState } from "react";
import type { OnPremStatus } from "../lib/cloudTypes";
import { t } from "../lib/i18n";
import { formatAgo, showNoPhoneHint } from "../lib/onprem";
import { ConfirmDialog } from "./ConfirmDialog";

interface Props {
  status: OnPremStatus;
  onRotate: () => Promise<void>;
}

/** Server state, QR code + address for the judges' phones, phones seen. */
export function OnPremServerPanel({ status, onRotate }: Props) {
  const [confirmRotate, setConfirmRotate] = useState(false);
  const [busy, setBusy] = useState(false);
  const [primary, ...others] = status.links;

  return (
    <section className="flex flex-col gap-3 rounded-2xl border border-ink-50/[0.06] bg-ink-700/40 px-5 py-4">
      <div className="flex items-center justify-between gap-2">
        <span className="label">{t.onprem.server}</span>
        <span
          className={[
            "rounded-full px-2.5 py-0.5 font-mono text-[10px] uppercase tracking-[0.18em] ring-1",
            status.running
              ? "bg-status-confirmed/15 text-status-confirmed ring-status-confirmed/30"
              : "bg-ink-50/5 text-ink-200 ring-ink-50/10",
          ].join(" ")}
        >
          {status.running && status.port != null ? t.onprem.serverRunning(status.port) : t.onprem.serverStopped}
        </span>
      </div>

      {status.error && (
        <p className="rounded-md bg-status-unknown/10 px-3 py-2 text-[12px] text-status-unknown">{status.error}</p>
      )}
      {!status.running && !status.error && (
        <p className="text-[12px] text-ink-200">{t.onprem.serverStoppedHint}</p>
      )}
      {status.running && !status.judgeUiBuilt && (
        <p className="rounded-md bg-status-armed/10 px-3 py-2 text-[12px] text-status-armed">{t.onprem.judgeUiMissing}</p>
      )}

      {status.running && (
        <>
          {primary ? (
            <div className="flex flex-col items-center gap-2">
              <div
                className="w-[240px] overflow-hidden rounded-xl bg-white p-2"
                // SVG generated by the Rust `qrcode` crate from our own URL.
                dangerouslySetInnerHTML={{ __html: primary.qrSvg }}
              />
              <p className="select-all break-all text-center font-mono text-[12px] text-ink-50">{primary.url}</p>
              <p className="text-center text-[12px] text-ink-200">{t.onprem.scanHint}</p>
            </div>
          ) : (
            <p className="rounded-md bg-status-armed/10 px-3 py-2 text-[12px] text-status-armed">{t.onprem.noAddress}</p>
          )}
          {others.length > 0 && (
            <details className="text-[12px] text-ink-200">
              <summary className="cursor-pointer">{t.onprem.otherAddresses}</summary>
              <ul className="mt-1 flex flex-col gap-1">
                {others.map((l) => (
                  <li key={l.address} className="select-all break-all font-mono text-[11px] text-ink-100">
                    {l.url}
                  </li>
                ))}
              </ul>
            </details>
          )}

          <div>
            <span className="label">{t.onprem.phones}</span>
            {status.clients.length === 0 ? (
              <p className="text-[12px] text-ink-200">{t.onprem.noPhones}</p>
            ) : (
              <ul className="mt-1 flex flex-col gap-0.5">
                {status.clients.map((c) => (
                  <li key={c.ip} className="flex justify-between font-mono text-[11px] text-ink-100">
                    <span>{c.ip}</span>
                    <span className="text-ink-200/70">{formatAgo(c.lastSeenSecs)}</span>
                  </li>
                ))}
              </ul>
            )}
          </div>
          {showNoPhoneHint(status) && (
            <p className="rounded-md bg-status-armed/10 px-3 py-2 text-[12px] text-status-armed">⚠ {t.onprem.noPhoneHint}</p>
          )}

          <button type="button" className="btn" disabled={busy} onClick={() => setConfirmRotate(true)}>
            {t.onprem.rotate}
          </button>
        </>
      )}

      {confirmRotate && (
        <ConfirmDialog
          title={t.onprem.rotate}
          tone="danger"
          confirmLabel={t.onprem.rotateConfirmAction}
          busy={busy}
          onCancel={() => setConfirmRotate(false)}
          onConfirm={async () => {
            setBusy(true);
            await onRotate();
            setBusy(false);
            setConfirmRotate(false);
          }}
        >
          <p>{t.onprem.rotateConfirm}</p>
        </ConfirmDialog>
      )}
    </section>
  );
}
