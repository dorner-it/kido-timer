use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    tauri_build::build();
    embed_judge_ui();
}

/// Embed the static judge UI (`frontend/dist-judge`, built by
/// `npm run build:judge`) into the binary. Generates
/// `$OUT_DIR/judge_assets.rs` with one `include_bytes!` per file. When the
/// folder is missing (no Node toolchain), nothing is embedded and the
/// server shows a placeholder page — `cargo build` always works. CI and the
/// release workflow build the judge UI first.
fn embed_judge_ui() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    println!("cargo:rerun-if-env-changed=KIDO_JUDGE_DIST");
    let dist = env::var_os("KIDO_JUDGE_DIST")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest.join("../../frontend/dist-judge"));
    println!("cargo:rerun-if-changed={}", dist.display());

    let mut files = Vec::new();
    let built = dist.join("index.html").is_file();
    if built {
        collect(&dist, &dist, &mut files);
        files.sort();
    } else {
        println!(
            "cargo:warning=judge UI not built ({} missing) — embedding placeholder; run `npm run build:judge` in frontend/",
            dist.join("index.html").display()
        );
    }

    let mut code = String::new();
    code.push_str("// @generated by build.rs — embedded static judge UI.\n");
    let _ = writeln!(code, "pub const JUDGE_UI_BUILT: bool = {built};");
    code.push_str("pub static JUDGE_ASSETS: &[(&str, &[u8])] = &[\n");
    for (rel, abs) in &files {
        let _ = writeln!(code, "    ({rel:?}, include_bytes!({abs:?})),");
    }
    code.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("judge_assets.rs");
    fs::write(out, code).expect("write judge_assets.rs");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.is_file() {
            let rel = path
                .strip_prefix(root)
                .expect("under root")
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            let abs = path
                .canonicalize()
                .unwrap_or(path.clone())
                .to_string_lossy()
                .into_owned();
            out.push((rel, abs));
        }
    }
}
